export function formatDateToDDMMMYY(dateInput: Date | string | number | null | undefined): string {
  if (!dateInput) return "";
  const d = new Date(dateInput);
  if (isNaN(d.getTime())) return "";

  const day = String(d.getDate()).padStart(2, "0");
  const month = MONTH_NAMES[d.getMonth()];
  const year = String(d.getFullYear()).slice(-2);

  return `${day}-${month}-${year}`;
}

export function parseDDMMMYYToISO(ddMmYyStr: string | null | undefined): string {
  if (!ddMmYyStr) return "";
  const trimmed = ddMmYyStr.trim();
  const match = trimmed.match(/^(\d{1,2})-([A-Za-z]{3})-(\d{2,4})$/);
  if (!match) {
    if (/^\d{4}-\d{2}-\d{2}$/.test(trimmed)) {
      return trimmed;
    }
    const d = new Date(trimmed);
    if (!isNaN(d.getTime())) {
      return d.toISOString().split("T")[0];
    }
    return "";
  }

  const day = match[1].padStart(2, "0");
  const monthStr = match[2].charAt(0).toUpperCase() + match[2].slice(1).toLowerCase();
  let year = match[3];

  if (year.length === 2) {
    year = `20${year}`;
  }

  const monthIndex = MONTH_NAMES.indexOf(monthStr);
  if (monthIndex === -1) return "";

  const month = String(monthIndex + 1).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

export function parseAnyDateToDDMMMYY(input: string | Date | number | null | undefined): string {
  if (!input) return "";
  if (input instanceof Date) {
    return formatDateToDDMMMYY(input);
  }

  const str = String(input).trim();
  if (!str) return "";

  const standard = /^(\d{1,2})-([A-Za-z]{3})-(\d{2,4})$/.exec(str);
  if (standard) {
    const day = standard[1].padStart(2, "0");
    const mmm = standard[2].charAt(0).toUpperCase() + standard[2].slice(1, 3).toLowerCase();
    const yr = standard[3].length === 4 ? standard[3].slice(-2) : standard[3];
    return `${day}-${mmm}-${yr}`;
  }

  const yyyyMMDD = /^(\d{4})-(\d{2})-(\d{2})/.exec(str);
  if (yyyyMMDD) {
    const yr = yyyyMMDD[1].slice(-2);
    const monthIdx = parseInt(yyyyMMDD[2], 10) - 1;
    const day = yyyyMMDD[3];
    const mmm = MONTH_NAMES[monthIdx] || yyyyMMDD[2];
    return `${day}-${mmm}-${yr}`;
  }

  const d = new Date(str);
  if (!isNaN(d.getTime())) {
    const yr = String(d.getFullYear()).slice(-2);
    const dy = String(d.getDate()).padStart(2, "0");
    const mmm = MONTH_NAMES[d.getMonth()];
    return `${dy}-${mmm}-${yr}`;
  }

  return str;
}

export function getMonthFromDate(dateStr: string): string {
  if (!dateStr) return "";
  const normalized = parseAnyDateToDDMMMYY(dateStr);
  if (!normalized) return "";
  const parts = normalized.split("-");
  if (parts.length === 3 && MONTH_NAMES.includes(parts[1])) {
    return `${parts[1]}-${parts[2]}`;
  }
  return "";
}

export function getTodayDDMMMYY(): string {
  const d = new Date();
  const year = String(d.getFullYear()).slice(-2);
  const day = String(d.getDate()).padStart(2, "0");
  const mmm = MONTH_NAMES[d.getMonth()];
  return `${day}-${mmm}-${year}`;
}

export function getCurrentMonthMMMYY(): string {
  const d = new Date();
  const year = String(d.getFullYear()).slice(-2);
  const mmm = MONTH_NAMES[d.getMonth()];
  return `${mmm}-${year}`;
}

export function getFormattedTimestamp(dateObj: Date = new Date()): string {
  const day = String(dateObj.getDate()).padStart(2, "0");
  const mmm = MONTH_NAMES[dateObj.getMonth()];
  const year = String(dateObj.getFullYear()).slice(-2);

  let hours = dateObj.getHours();
  const minutes = String(dateObj.getMinutes()).padStart(2, "0");
  const ampm = hours >= 12 ? "PM" : "AM";
  hours = hours % 12;
  hours = hours ? hours : 12;
  const strHours = String(hours).padStart(2, "0");

  return `${day}-${mmm}-${year}, ${strHours}:${minutes} ${ampm}`;
}

/**
 * Calculates lead age in days from lead creation date or timestamp
 */
export function calculateLeadAge(createdDateOrStr: string | Date | undefined | null): string {
  if (!createdDateOrStr) return "0 days";
  let createdDate: Date;
  if (createdDateOrStr instanceof Date) {
    createdDate = createdDateOrStr;
  } else {
    const iso = parseDDMMMYYToISO(createdDateOrStr);
    createdDate = iso ? new Date(iso) : new Date(createdDateOrStr);
  }

  if (isNaN(createdDate.getTime())) return "0 days";

  const diffMs = Date.now() - createdDate.getTime();
  if (diffMs <= 0) return "0 days";

  const days = Math.floor(diffMs / (1000 * 60 * 60 * 24));
  return `${days} ${days === 1 ? "day" : "days"}`;
}


/**
 * Calculates Lead Score dynamically out of 100 based on 6 clinical & demographic criteria:
 * 1. Husband Age (max 25 pts)
 * 2. Wife Age (max 25 pts)
 * 3. Medical Condition (max 5 pts)
 * 4. Married Since (max 15 pts)
 * 5. How long trying to conceive (max 15 pts)
 * 6. When are you planning to start treatment (max 15 pts)
 */
export function calculateLeadScore(params: {
  husbandAge?: string | number;
  wifeAge?: string | number;
  preMedicalConditions?: string;
  marriedSince?: string | number;
  tryingToConceiveYears?: string | number;
  whenPlanningToStartTreatment?: string;
}): string {
  let score = 0;

  // 1. Husband Age (max 25)
  // 21 - 25: 3 | 25 - 30: 4 | 30 - 40: 5 | 40 - 50: 6 | > 50: 7 (Weightage total: 25)
  const hAge = parseInt(String(params.husbandAge || "").replace(/\D/g, ""), 10);
  if (!isNaN(hAge) && hAge > 0) {
    if (hAge >= 21 && hAge < 25) score += 3;
    else if (hAge >= 25 && hAge < 30) score += 4;
    else if (hAge >= 30 && hAge < 40) score += 5;
    else if (hAge >= 40 && hAge <= 50) score += 6;
    else if (hAge > 50) score += 7;
  }

  // 2. Wife Age (max 25)
  // 21 - 25: 4 | 25 - 30: 5 | 30 - 40: 7 | 40 - 50: 9
  const wAge = parseInt(String(params.wifeAge || "").replace(/\D/g, ""), 10);
  if (!isNaN(wAge) && wAge > 0) {
    if (wAge >= 21 && wAge < 25) score += 4;
    else if (wAge >= 25 && wAge < 30) score += 5;
    else if (wAge >= 30 && wAge < 40) score += 7;
    else if (wAge >= 40) score += 9;
  }

  // 3. Medical Condition (max 5)
  // Yes: 5 | No: 0
  const med = String(params.preMedicalConditions || "").trim().toLowerCase();
  if (med === "yes") {
    score += 5;
  }

  // 4. Married Since (max 15)
  // 0 - 2: 1 | 2 - 5: 2 | 5 - 8: 3 | 8 - 10: 4 | > 10: 5
  const ms = parseInt(String(params.marriedSince || "").replace(/\D/g, ""), 10);
  if (!isNaN(ms) && ms >= 0) {
    if (ms <= 2) score += 1;
    else if (ms > 2 && ms <= 5) score += 2;
    else if (ms > 5 && ms <= 8) score += 3;
    else if (ms > 8 && ms <= 10) score += 4;
    else if (ms > 10) score += 5;
  }

  // 5. How long trying to conceive (max 15)
  // 0 - 2: 1 | 2 - 5: 2 | 5 - 8: 3 | 8 - 10: 4 | > 10: 5
  const ttc = parseInt(String(params.tryingToConceiveYears || "").replace(/\D/g, ""), 10);
  if (!isNaN(ttc) && ttc >= 0) {
    if (ttc <= 2) score += 1;
    else if (ttc > 2 && ttc <= 5) score += 2;
    else if (ttc > 5 && ttc <= 8) score += 3;
    else if (ttc > 8 && ttc <= 10) score += 4;
    else if (ttc > 10) score += 5;
  }

  // 6. When are you planning to start treatment (max 15)
  // Immediately: 5 | This Month: 4 | 1 - 2 Months: 3 | >2 Months: 2 | Not Decided: 1
  const when = String(params.whenPlanningToStartTreatment || "").trim().toLowerCase();
  if (when.includes("immediately")) score += 5;
  else if (when.includes("this month") || when.includes("within 1 month")) score += 4;
  else if (when.includes("1 - 2 months") || when.includes("1-2 months") || when.includes("within 2-3 months") || when.includes("1-3 months")) score += 3;
  else if (when.includes(">2 months") || when.includes("after 3 months") || when.includes("3-6 months") || when.includes("more than 6 months")) score += 2;
  else if (when.includes("not decided") || when.includes("exploring")) score += 1;

  return String(score);
}
